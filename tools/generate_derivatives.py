#!/usr/bin/env python3
"""
generate_derivatives.py — emit exact higher-order directional-derivative code for a pure
(CppAD-free) yabi-bdf UserODERHS backend.

This is an OPTIONAL, decoupled developer tool.  It does not build into the solver and the
solver never knows it exists: it emits plain C++ in the exact UserODERHS hook signatures, and
you wire the output in by hand, e.g.

    #include "generated_myode.hpp"
    rhs.setJacobianVectorProduct(...);                       # if you want matrix-free
    rhs.setOrderKDirectional(generated::orderKDirectional);  # the higher-order forward hook

The emitted `orderKDirectional(k, x, S, result)` returns the k-th-order *nonlinear source* of
the vector RHS,  source_k = k! y^(k) - J(x) S_k,  which is what BDFIntegrator::forwardOrder(k)
needs for order k >= 2.  It is exact (analytic) — no finite differences anywhere.

How it works: for a jet  y(tau) = y + S1 tau + (S2/2!) tau^2 + ... + (Sk/k!) tau^k, expand
f(y(tau)) symbolically, take the tau^k coefficient, and subtract the linear term J*S_k.

Run:
    python3 generate_derivatives.py            # emit the demo ODE's code to stdout
    python3 generate_derivatives.py --check    # numerically verify against hand-derived H/T

Prerequisites: sympy (pip install --user --break-system-packages sympy; see PEP 668).
"""

import sys
import sympy as sp

# ----------------------------------------------------------------------------------
#  ODE specification — edit these three to describe your system f(y), y in R^n.
# ----------------------------------------------------------------------------------
N = 2  # number of state variables
Y = sp.symbols("y0 y1")  # n state symbols
# Right-hand side f(y), one expression per component (may depend on t and params too,
# but the *directions* below are state-only, matching forwardOrder's state seed).
F = [
    Y[0] ** 2 * Y[1],  # y0' = y0^2 * y1   (cubic, so order-2 and -3 sources are nonzero)
    Y[0] * Y[1] ** 2,  # y1' = y0 * y1^2
]
MAX_ORDER = 4  # emit sources for k = 2 .. MAX_ORDER


def directional_sources(f_list, y_list, max_order):
    """Return {k: [source_k component expressions]} for k = 2..max_order."""
    n = len(y_list)
    tau = sp.symbols("tau")
    S = [[sp.symbols(f"S{m}_{i}") for i in range(n)] for m in range(1, max_order + 1)]

    # Jet: Y_i(tau) = y_i + sum_m S_m_i / m! * tau^m
    Ytau = []
    for i in range(n):
        expr = y_list[i]
        f_ = 1
        for m in range(1, max_order + 1):
            f_ *= m
            expr += S[m - 1][i] / f_ * tau**m
        Ytau.append(expr)

    # Jacobian J[j][i] = df_j / dy_i
    J = [[sp.diff(fj, y_list[i]) for i in range(n)] for fj in f_list]

    sources = {}
    for k in range(2, max_order + 1):
        kfac = sp.factorial(k)
        src = []
        for j, fj in enumerate(f_list):
            Ftau = sp.expand(fj.subs({y_list[i]: Ytau[i] for i in range(n)}))
            coeff_k = sp.Poly(Ftau, tau).coeff_monomial(tau**k)
            # J * S_k (linear term) for component j
            linear = sum(J[j][i] * S[k - 1][i] for i in range(n))
            src.append(sp.expand(kfac * coeff_k - linear))
        sources[k] = src
    return sources, J, S


def ccode_with_cse(exprs):
    """CSE a list of expressions and emit C statements writing result[0..n-1]."""
    common, reduced = sp.cse(exprs, symbols=sp.numbered_symbols('cse'))
    lines = []
    for name, expr in common:
        lines.append(f"    const double {name} = {sp.ccode(expr)};")
    for i, expr in enumerate(reduced):
        lines.append(f"    result[{i}] = {sp.ccode(expr)};")
    return lines


def emit(f_list, y_list, max_order):
    n = len(y_list)
    sources, J, S = directional_sources(f_list, y_list, max_order)

    out = []
    out.append("// Auto-generated by tools/generate_derivatives.py — do not edit by hand.")
    out.append("#pragma once")
    out.append("#include <cmath>")
    out.append("")
    out.append("namespace generated {")
    out.append(f"constexpr unsigned n = {n};")
    out.append("")

    ysym = [sp.Symbol(f"y[{i}]") for i in range(n)]
    xsym = [sp.Symbol(f"x[{i}]") for i in range(n)]
    y_to_y = {y_list[i]: ysym[i] for i in range(n)}
    y_to_x = {y_list[i]: xsym[i] for i in range(n)}

    out.append("// f(y, F): ODE right-hand side, n entries.")
    out.append("inline void f(const double* y, double* F) {")
    for j, fj in enumerate(f_list):
        out.append(f"    F[{j}] = {sp.ccode(fj.subs(y_to_y))};")
    out.append("}")
    out.append("")
    out.append("// jacobian(y, Jm): column-major J[i + n*j] = df_i/dy_j, n*n entries.")
    out.append("inline void jacobian(const double* y, double* Jm) {")
    for j, fj in enumerate(f_list):  # row j = df_j
        for i in range(n):           # column i = /dy_i
            out.append(f"    Jm[{j} + n*{i}] = {sp.ccode(sp.diff(fj, y_list[i]).subs(y_to_y))};")
    out.append("}")
    out.append("")
    out.append("// orderKDirectional(k, x, S, result): k-th-order nonlinear source,")
    out.append("// result = k! y^(k) - J(x) S_k.  x: full argument (state [time params]);")
    out.append("// S: k*n flattened directions S[m*n+i] = S_{m+1}[i]; result: n entries.")
    out.append("inline void orderKDirectional(unsigned k, const double* x, const double* S, double* result) {")
    out.append("    (void)x;")
    out.append("    switch (k) {")
    for k in sorted(sources):
        out.append(f"    case {k}: {{")
        # Substitute direction symbols S_m_i -> S[(m-1)*n + i] and state y_i -> x[i].
        subst = dict(y_to_x)
        for m in range(1, k + 1):
            for i in range(n):
                subst[sp.symbols(f"S{m}_{i}")] = sp.symbols(f"S[{(m-1)*n + i}]")
        exprs = [src.subs(subst) for src in sources[k]]
        for line in ccode_with_cse(exprs):
            out.append(line)
        out.append("    } break;")
    out.append("    default:")
    out.append("        for (unsigned i = 0; i < n; ++i) result[i] = 0.0;")
    out.append("        break;")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("} // namespace generated")
    return "\n".join(out)


def check(f_list, y_list, max_order):
    """Numerically verify source_2 and source_3 against hand-derived H and T."""
    n = len(y_list)
    sources, J, S = directional_sources(f_list, y_list, max_order)
    # Demo test point and directions.
    yv = {y_list[i]: v for i, v in enumerate([2.0, 3.0])}
    Sv = {}
    for m in range(1, max_order + 1):
        for i in range(n):
            Sv[S[m - 1][i]] = 0.1 * ((m - 1) * n + i + 1)

    # Hand-derived for f0 = y0^2 y1, f1 = y0 y1^2:
    #   H(S1,S1):  f0: 2 S1_0^2 y1 + 4 S1_0 S1_1 y0 ;  f1: 4 S1_0 S1_1 y1 + 2 S1_1^2 y0
    #   3H(S1,S2)+T: computed from derivatives of f0/f1 (see spike B).
    S1 = [S[0][i] for i in range(n)]
    S2 = [S[1][i] for i in range(n)]
    y0, y1 = y_list
    hand2 = [
        2 * S1[0] ** 2 * y1 + 4 * S1[0] * S1[1] * y0,
        4 * S1[0] * S1[1] * y1 + 2 * S1[1] ** 2 * y0,
    ]
    hand3 = [
        6 * S1[0] ** 2 * S1[1] + 6 * S1[0] * S2[0] * y1 + 6 * S1[0] * S2[1] * y0
        + 6 * S1[1] * S2[0] * y0,
        6 * S1[0] * S1[1] ** 2 + 6 * S1[0] * S2[1] * y1 + 6 * S1[1] * S2[0] * y1
        + 6 * S1[1] * S2[1] * y0,
    ]
    ok = True
    for k, hand in [(2, hand2), (3, hand3)]:
        for j in range(n):
            got = float(sources[k][j].subs({**yv, **Sv}))
            exp = float(hand[j].subs({**yv, **Sv}))
            status = "OK" if abs(got - exp) < 1e-12 else "FAIL"
            if status == "FAIL":
                ok = False
            print(f"  source_{k}[{j}]: got={got:.15g} hand={exp:.15g} {status}")
    print("CHECK", "PASS" if ok else "FAIL")
    return ok


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        ok = check(F, Y, MAX_ORDER)
        sys.exit(0 if ok else 1)
    print(emit(F, Y, MAX_ORDER))

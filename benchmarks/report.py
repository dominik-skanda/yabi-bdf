#!/usr/bin/env python3
"""
report.py — regenerate the test-evidence report (T44) from the telemetry harness.

Runs `yabi_telemetry` (the machine-readable benchmark harness), parses its CSV,
and writes:
  - benchmarks/telemetry.csv        the raw table
  - benchmarks/TELEMETRY.md         a human-readable Markdown table
  - benchmarks/work_precision.png   the error-vs-rtol work-precision plot

The reference solutions the telemetry compares against are from an independent
source (SciPy Radau, rtol=1e-13) and are recorded in telemetry.cpp — never a
YABI self-reference.

Usage:  python3 benchmarks/report.py [path-to-yabi_telemetry]
"""

import csv
import io
import subprocess
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
DEFAULT_BINARY = ROOT / "build" / "yabi_telemetry"


def run_telemetry(binary: Path) -> str:
    return subprocess.run([str(binary)], capture_output=True, text=True, check=True).stdout


def parse(rows):
    data = {}
    for row in rows:
        name = row["benchmark"]
        data.setdefault(name, []).append(row)
    return data


def write_table(path: Path, data) -> None:
    lines = [
        "# YABI test-evidence telemetry (T44)",
        "",
        "Machine-generated by `benchmarks/report.py` from `benchmarks/telemetry.cpp`.",
        "Reference solutions are from SciPy Radau (`rtol=1e-13`, independent solver).",
        "",
        "| benchmark | rtol | max rel. error | runtime (ms) | J-evals | factorizations | steps | order |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name in sorted(data):
        for row in data[name]:
            lines.append(
                f"| {row['benchmark']} | {float(row['rtol']):.0e} | {float(row['error']):.3e} "
                f"| {float(row['runtime_ms']):.2f} | {row['jacobian_evals']} "
                f"| {row['factorizations']} | {row['steps']} | {row['order']} |"
            )
    lines.append("")
    path.write_text("\n".join(lines))


def write_plot(path: Path, data) -> None:
    plt.figure(figsize=(7, 5))
    for name in sorted(data):
        rtol = [float(r["rtol"]) for r in data[name]]
        err = [float(r["error"]) for r in data[name]]
        plt.loglog(rtol, err, "o-", label=name)
    # Ideal slope line (error == rtol).
    lo = min(float(r["rtol"]) for rows in data.values() for r in rows)
    hi = max(float(r["rtol"]) for rows in data.values() for r in rows)
    plt.loglog([lo, hi], [lo, hi], "--", color="gray", alpha=0.6, label="ideal (error = rtol)")
    plt.xlabel("requested relative tolerance (rtol)")
    plt.ylabel("max relative error vs Radau reference")
    plt.title("YABI work-precision")
    plt.grid(True, which="both", ls="--", alpha=0.4)
    plt.legend()
    plt.tight_layout()
    plt.savefig(path, dpi=150)


def main() -> None:
    binary = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_BINARY
    stdout = run_telemetry(binary)
    rows = list(csv.DictReader(io.StringIO(stdout)))
    data = parse(rows)
    (HERE / "telemetry.csv").write_text(stdout)
    write_table(HERE / "TELEMETRY.md", data)
    write_plot(HERE / "work_precision.png", data)
    print(f"wrote {len(rows)} rows -> telemetry.csv, TELEMETRY.md, work_precision.png")


if __name__ == "__main__":
    main()
